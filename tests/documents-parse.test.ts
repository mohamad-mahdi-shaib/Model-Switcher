import { test } from "node:test";
import { MAX_DOCUMENT_CHARS, MAX_SHEET_ROWS } from "@/lib/documents";
import assert from "node:assert/strict";
import * as XLSX from "xlsx";
import { Document, Packer, Paragraph, HeadingLevel } from "docx";
import { parseDocument, sniffDocumentKind, looksBinary, DocumentParseError } from "@/server/documents/parse";
import { chunkSections } from "@/server/documents/embed";
import { documentKindFromName, validateDocumentFile, MAX_DOCUMENT_BYTES } from "@/lib/documents";

/**
 * Project 4: parser tests against REAL files.
 *
 * Every binary fixture here is generated by the same libraries a user's file
 * would come from -- a genuine XLSX written by SheetJS, a genuine DOCX
 * written by `docx`, a genuine PDF written by jsPDF -- and then parsed back
 * by the real parser. Nothing is stubbed: a test that fed the parser a
 * hand-written string would prove nothing about whether it can read an actual
 * Office document.
 */

const enc = (s: string) => new TextEncoder().encode(s);

/* ------------------------------------------------------- type sniffing --- */

test("extension mapping covers every required format", () => {
  const expected: [string, string][] = [
    ["report.pdf", "pdf"], ["notes.docx", "docx"], ["books.xlsx", "xlsx"],
    ["data.csv", "csv"], ["readme.md", "markdown"], ["notes.txt", "text"],
    ["app.ts", "code"], ["main.py", "code"], ["Main.java", "code"],
    ["lib.rs", "code"], ["api.go", "code"], ["index.php", "code"],
    ["Program.cs", "code"], ["query.sql", "code"], ["data.json", "code"],
    ["conf.yaml", "code"], ["conf.yml", "code"], ["page.html", "code"],
    ["style.css", "code"], ["a.c", "code"], ["b.cpp", "code"], ["c.jsx", "code"],
  ];
  for (const [name, kind] of expected) {
    assert.equal(documentKindFromName(name), kind, name);
  }
  assert.equal(documentKindFromName("virus.exe"), null);
  assert.equal(documentKindFromName("noextension"), null);
});

test("a file whose bytes contradict its extension is refused", () => {
  // A ZIP wearing a .pdf extension: the single most common disguise.
  const zipBytes = new Uint8Array([0x50, 0x4b, 0x03, 0x04, 1, 2, 3]);
  assert.equal(sniffDocumentKind(zipBytes, "evil.pdf"), null);
  // And the reverse.
  const pdfBytes = enc("%PDF-1.7\n...");
  assert.equal(sniffDocumentKind(pdfBytes, "evil.docx"), null);
  // Correct pairings still pass.
  assert.equal(sniffDocumentKind(pdfBytes, "real.pdf"), "pdf");
  assert.equal(sniffDocumentKind(zipBytes, "real.docx"), "docx");
});

test("binary content masquerading as source code is refused", () => {
  const withNul = new Uint8Array([0x4d, 0x5a, 0x00, 0x01, 0x02]);
  assert.equal(looksBinary(withNul), true);
  assert.equal(sniffDocumentKind(withNul, "payload.js"), null);
  assert.equal(looksBinary(enc("const x = 1;\n")), false);
});

test("size and count limits are enforced before any parsing", () => {
  assert.equal(validateDocumentFile({ name: "a.pdf", size: 10 }).ok, true);
  const big = validateDocumentFile({ name: "a.pdf", size: MAX_DOCUMENT_BYTES + 1 });
  assert.equal(big.ok, false);
  assert.equal(big.ok === false && big.reason, "tooLarge");
  const empty = validateDocumentFile({ name: "a.pdf", size: 0 });
  assert.equal(empty.ok === false && empty.reason, "empty");
  const many = validateDocumentFile({ name: "a.pdf", size: 10 }, 10);
  assert.equal(many.ok === false && many.reason, "tooMany");
  const bad = validateDocumentFile({ name: "a.exe", size: 10 });
  assert.equal(bad.ok === false && bad.reason, "unsupportedType");
});

/* ------------------------------------------------------------- XLSX ------ */

test("a REAL xlsx round-trips: sheets, rows and A1-style citations", async () => {
  const rows = [
    ["Item", "Qty", "Price"],
    ["Widget", 10, 9.99],
    ["Gadget", 3, 24.5],
    ["Doohickey", 7, 1.25],
  ];
  const sheet = XLSX.utils.aoa_to_sheet(rows);
  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, sheet, "Inventory");
  const buffer: Buffer = XLSX.write(workbook, { type: "buffer", bookType: "xlsx" });

  const parsed = await parseDocument(new Uint8Array(buffer), "stock.xlsx");
  assert.equal(parsed.kind, "xlsx");
  assert.deepEqual(parsed.meta.sheets, ["Inventory"]);
  assert.ok(parsed.sections.length >= 1);

  const section = parsed.sections[0];
  assert.equal(section.sheet, "Inventory");
  // The citation must name the real sheet and a real row range.
  assert.match(section.ref, /^Inventory!A2:C\d+$/);
  // The header row is repeated into the body so a retrieved chunk is readable.
  assert.match(section.text, /Item\tQty\tPrice/);
  assert.match(section.text, /Gadget/);
  assert.equal(section.rowStart, 2);
});

/* ------------------------------------------------------------- CSV ------- */

test("a REAL csv parses with row-range citations", async () => {
  const csv = "name,role\nAda,engineer\nGrace,admiral\nAlan,logician\n";
  const parsed = await parseDocument(enc(csv), "people.csv");
  assert.equal(parsed.kind, "csv");
  assert.ok(parsed.sections.length >= 1);
  assert.match(parsed.sections[0].ref, /^rows \d+-\d+$/);
  assert.match(parsed.sections[0].text, /name\trole/);
  assert.match(parsed.sections[0].text, /Grace\tadmiral/);
});

/* ------------------------------------------------------------- DOCX ------ */

test("a REAL docx round-trips, keeping headings as section anchors", async () => {
  const doc = new Document({
    sections: [
      {
        children: [
          new Paragraph({ text: "Quarterly Report", heading: HeadingLevel.HEADING_1 }),
          new Paragraph("Revenue rose by twelve percent across the period."),
          new Paragraph({ text: "Risks", heading: HeadingLevel.HEADING_2 }),
          new Paragraph("Supply chain delays remain the principal risk."),
        ],
      },
    ],
  });
  const buffer = await Packer.toBuffer(doc);

  const parsed = await parseDocument(new Uint8Array(buffer), "report.docx");
  assert.equal(parsed.kind, "docx");
  assert.ok(parsed.sections.length >= 1, "expected at least one section");

  const all = parsed.sections.map((s) => s.text).join("\n");
  assert.match(all, /Revenue rose by twelve percent/);
  assert.match(all, /Supply chain delays/);
  // At least one section is anchored to a real heading from the document.
  assert.ok(
    parsed.sections.some((s) => s.heading === "Quarterly Report" || s.heading === "Risks"),
    "headings should become section anchors",
  );
});

/* -------------------------------------------------------------- PDF ------ */

test("a REAL pdf round-trips with per-page citations", async () => {
  const { jsPDF } = await import("jspdf");
  const pdf = new jsPDF();
  pdf.text("Alpha page content about turbines", 10, 20);
  pdf.addPage();
  pdf.text("Beta page content about gearboxes", 10, 20);
  const bytes = new Uint8Array(pdf.output("arraybuffer") as ArrayBuffer);

  const parsed = await parseDocument(bytes, "machines.pdf");
  assert.equal(parsed.kind, "pdf");
  assert.equal(parsed.meta.pages, 2, "both pages should be counted");
  assert.ok(parsed.sections.length >= 2, "expected a section per page");

  const page1 = parsed.sections.find((s) => s.page === 1);
  const page2 = parsed.sections.find((s) => s.page === 2);
  assert.ok(page1 && page2, "both pages should yield text");
  assert.equal(page1.ref, "p. 1");
  assert.equal(page2.ref, "p. 2");
  assert.match(page1.text, /turbines/);
  assert.match(page2.text, /gearboxes/);
});

test("a pdf with no selectable text is reported as scanned, not silently empty", async () => {
  const { jsPDF } = await import("jspdf");
  const pdf = new jsPDF(); // one page, no text drawn at all
  const bytes = new Uint8Array(pdf.output("arraybuffer") as ArrayBuffer);

  const parsed = await parseDocument(bytes, "scan.pdf");
  assert.equal(parsed.sections.length, 0);
  assert.ok(parsed.warnings.length > 0, "a text-free PDF must produce a warning");
  assert.match(parsed.warnings.join(" "), /scanned|selectable text/i);
});

/* ------------------------------------------------- text / markdown / code */

test("code files split on line boundaries with line-range citations", async () => {
  const code = Array.from({ length: 200 }, (_, i) => `const value${i} = ${i};`).join("\n");
  const parsed = await parseDocument(enc(code), "generated.ts");
  assert.equal(parsed.kind, "code");
  assert.ok(parsed.sections.length >= 2, "a long file should split");
  const first = parsed.sections[0];
  assert.match(first.ref, /^lines 1-\d+$/);
  assert.equal(first.lineStart, 1);
  // Ranges must be contiguous and non-overlapping, or a citation is a lie.
  for (let i = 1; i < parsed.sections.length; i += 1) {
    assert.equal(
      parsed.sections[i].lineStart,
      (parsed.sections[i - 1].lineEnd ?? 0) + 1,
      "line ranges must be contiguous",
    );
  }
});

test("markdown and plain text parse with their own kinds", async () => {
  const md = await parseDocument(enc("# Title\n\nSome prose here.\n"), "doc.md");
  assert.equal(md.kind, "markdown");
  assert.match(md.sections[0].text, /Some prose here/);

  const txt = await parseDocument(enc("just a note\n"), "note.txt");
  assert.equal(txt.kind, "text");
  assert.match(txt.sections[0].text, /just a note/);
});

/* --------------------------------------------------------- failure paths - */

test("an empty file is rejected with a usable message", async () => {
  await assert.rejects(
    () => parseDocument(new Uint8Array(0), "empty.txt"),
    (error: unknown) => error instanceof DocumentParseError && /empty/i.test((error as Error).message),
  );
});

test("a whitespace-only text file is rejected rather than indexed as nothing", async () => {
  await assert.rejects(
    () => parseDocument(enc("   \n\n  \t "), "blank.txt"),
    (error: unknown) => error instanceof DocumentParseError,
  );
});

test("a corrupt docx fails with a message, not a raw library stack", async () => {
  // A valid ZIP header followed by garbage: passes sniffing, fails parsing.
  const broken = new Uint8Array([0x50, 0x4b, 0x03, 0x04, ...new Array(64).fill(0x41)]);
  await assert.rejects(
    () => parseDocument(broken, "broken.docx"),
    (error: unknown) => {
      assert.ok(error instanceof DocumentParseError);
      const message = (error as Error).message;
      assert.match(message, /Word file could not be read/);
      assert.doesNotMatch(message, /at .*\(/, "no stack frame may reach the message");
      return true;
    },
  );
});

test("a mislabelled file is refused before reaching a parser", async () => {
  await assert.rejects(
    () => parseDocument(enc("not a pdf at all"), "fake.pdf"),
    (error: unknown) =>
      error instanceof DocumentParseError && /do not match its file extension/.test((error as Error).message),
  );
});

/* ============================ large documents ============================ */

/**
 * Acceptance criterion: "Large documents handled without errors."
 *
 * Every fixture here is genuinely larger than a model's context window, and
 * larger than this app's own ceilings, so the behaviour under test is what
 * happens AT the limit -- not whether a big file is merely accepted.
 *
 * The property that matters is not "it survives": it is that a partial read
 * is REPORTED. A document silently truncated to 1.5M characters, answered
 * from as though complete, is the failure mode worth guarding against.
 */

const LOREM =
  "Lorem ipsum dolor sit amet, consectetur adipiscing elit, sed do eiusmod tempor incididunt ut labore et dolore magna aliqua. ";

test("a 2M-character document is capped, and SAYS it was capped", async () => {
  const bytes = new TextEncoder().encode((LOREM.repeat(20) + "\n\n").repeat(850));
  assert.ok(bytes.length > 2_000_000, "fixture must exceed the char ceiling");

  const parsed = await parseDocument(bytes, "huge.txt");
  assert.equal(parsed.meta.chars, MAX_DOCUMENT_CHARS, "read exactly up to the ceiling");
  assert.equal(parsed.meta.truncated, true);
  assert.ok(
    parsed.warnings.some((w) => /first 1,500,000 characters/.test(w)),
    `truncation must be reported: ${JSON.stringify(parsed.warnings)}`,
  );
});

test("a capped document still chunks cleanly, every chunk citable", async () => {
  const bytes = new TextEncoder().encode((LOREM.repeat(20) + "\n\n").repeat(850));
  const parsed = await parseDocument(bytes, "huge.txt");
  const chunks = chunkSections(parsed.sections);

  assert.ok(chunks.length > 100, `expected many chunks, got ${chunks.length}`);
  for (const chunk of chunks) {
    assert.ok(chunk.ref.length > 0, "a chunk with no citation cannot be quoted back");
    assert.ok(chunk.text.length <= 6_000, `chunk too large to embed: ${chunk.text.length}`);
  }
});

test("a 12,000-row spreadsheet stops at the row cap and names the sheet", async () => {
  const XLSX = await import("xlsx");
  const rows: (string | number)[][] = [["ID", "Region", "Revenue"]];
  for (let i = 1; i <= 12_000; i += 1) rows.push([i, `Region ${i % 20}`, i * 13.5]);
  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, XLSX.utils.aoa_to_sheet(rows), "Big");
  const bytes = new Uint8Array(XLSX.write(workbook, { bookType: "xlsx", type: "array" }));

  const parsed = await parseDocument(bytes, "huge.xlsx");
  assert.equal(parsed.meta.rows, MAX_SHEET_ROWS);
  assert.equal(parsed.meta.truncated, true);
  assert.ok(
    parsed.warnings.some((w) => /Big/.test(w) && /5,000/.test(w)),
    `the sheet and the cap must both be named: ${JSON.stringify(parsed.warnings)}`,
  );
  // Still usable: every surviving row block is citable to a cell range.
  const chunks = chunkSections(parsed.sections);
  assert.ok(chunks.length > 0);
  assert.ok(chunks.every((chunk) => /Big!/.test(chunk.ref)), "A1-style refs survive truncation");
});

test("a large DOCX and a large code file are read in full, under the ceiling", async () => {
  const { Document, Packer, Paragraph, HeadingLevel } = await import("docx");
  const children = [];
  for (let section = 0; section < 40; section += 1) {
    children.push(new Paragraph({ heading: HeadingLevel.HEADING_2, text: `Section ${section}` }));
    for (let p = 0; p < 10; p += 1) children.push(new Paragraph(`S${section}P${p}: ${LOREM.repeat(12)}`));
  }
  const docx = new Uint8Array(await Packer.toBuffer(new Document({ sections: [{ children }] })));
  const parsedDocx = await parseDocument(docx, "huge.docx");
  assert.ok(parsedDocx.meta.chars > 500_000, `expected a big document: ${parsedDocx.meta.chars}`);
  assert.equal(parsedDocx.meta.truncated, false, "under the ceiling, so nothing is dropped");
  assert.ok(parsedDocx.sections.length > 100);

  const code = Array.from(
    { length: 9_000 },
    (_, i) => `export function fn${i}(a: number): number { return a * ${i} + 1; }`,
  ).join("\n");
  const parsedCode = await parseDocument(new TextEncoder().encode(code), "huge.ts");
  assert.ok(parsedCode.meta.chars > 500_000);
  assert.equal(parsedCode.kind, "code");
  assert.ok(parsedCode.sections.every((s) => /lines \d+-\d+/.test(s.ref)), "line-range refs throughout");
});
